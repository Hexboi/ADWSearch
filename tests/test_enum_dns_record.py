"""Binary dnsRecord parser tests — one fixture per RRTYPE.

Hex vectors were generated by encoding [MS-DNSP] examples with impacket.Structure and
are stable across runs.
"""

from adwsearch.enum.dns_record import parse_dns_record


def test_parse_a_record():
    raw = bytes.fromhex("0400010005f000000100000000000e1000000000000000000a000001")
    out = parse_dns_record(raw)
    assert out == {"type": "A", "data": "10.0.0.1", "ttl_seconds": 3600}


def test_parse_aaaa_record():
    raw = bytes.fromhex(
        "10001c0005f000000100000000000e10000000000000000000000000000000000000000000000001"
    )
    out = parse_dns_record(raw)
    assert out == {"type": "AAAA", "data": "::1", "ttl_seconds": 3600}


def test_parse_cname_record():
    raw = bytes.fromhex(
        "1300050005f00000010000000000012c00000000000000001103046463303104636f7270056c6f63616c00"
    )
    out = parse_dns_record(raw)
    assert out == {"type": "CNAME", "data": "dc01.corp.local", "ttl_seconds": 300}


def test_parse_mx_record():
    raw = bytes.fromhex(
        "15000f0005f00000010000000000012c0000000000000000000a1103046d61696c04636f7270056c6f63616c00"
    )
    out = parse_dns_record(raw)
    assert out["type"] == "MX"
    assert out["ttl_seconds"] == 300
    assert out["data"] == {"preference": 10, "name": "mail.corp.local"}


def test_parse_srv_record():
    raw = bytes.fromhex(
        "1900210005f00000010000000000012c00000000000000000000006400581103046463303104636f7270056c6f63616c00"
    )
    out = parse_dns_record(raw)
    assert out["type"] == "SRV"
    assert out["data"] == {
        "priority": 0, "weight": 100, "port": 88, "target": "dc01.corp.local",
    }


def test_parse_txt_record():
    raw = bytes.fromhex(
        "0600100005f00000010000000000012c00000000000000000568656c6c6f"
    )
    out = parse_dns_record(raw)
    assert out == {"type": "TXT", "data": "hello", "ttl_seconds": 300}


def test_parse_soa_record():
    raw = bytes.fromhex(
        "3b00060005f000000100000000000e1000000000000000000000000100000384000002580001518000"
        "000e101103046463303104636f7270056c6f63616c0012030561646d696e04636f7270056c6f63616c00"
    )
    out = parse_dns_record(raw)
    assert out["type"] == "SOA"
    assert out["ttl_seconds"] == 3600
    soa = out["data"]
    assert soa["serial"] == 1
    assert soa["refresh"] == 900
    assert soa["retry"] == 600
    assert soa["expire"] == 86400
    assert soa["minimum_ttl"] == 3600
    assert soa["primary_server"] == "dc01.corp.local"
    assert soa["admin_email"] == "admin.corp.local"


def test_parse_unknown_type_falls_back_to_hex():
    # Type = 0xFF (not in the known set). Payload is 4 bytes of 0xAB.
    raw = bytes.fromhex("0400ff0005f000000100000000000e100000000000000000abababab")
    out = parse_dns_record(raw)
    assert out["type"] == 0xFF
    assert out["data"] == "abababab"
